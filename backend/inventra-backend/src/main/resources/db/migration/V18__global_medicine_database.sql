-- V18: Global Medicine Database (GMD) and Retailer Suggestion Pipeline
-- =========================================================================

-- 1. Global Medicines Table (Platform-wide curated master database)
CREATE TABLE IF NOT EXISTS global_medicines (
    id UUID PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    generic_name VARCHAR(255) NOT NULL,
    brand_name VARCHAR(100),
    manufacturer VARCHAR(150),
    dosage_form VARCHAR(50) NOT NULL,
    strength VARCHAR(50),
    base_unit VARCHAR(30) NOT NULL,
    selling_unit VARCHAR(50) NOT NULL DEFAULT 'Unit',
    units_per_selling_unit INTEGER NOT NULL DEFAULT 1,
    hsn_code VARCHAR(20),
    tax_rate NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    prescription_required BOOLEAN NOT NULL DEFAULT FALSE,
    category_name VARCHAR(100),
    barcode VARCHAR(100),
    description TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_global_units_per_selling_unit_positive CHECK (units_per_selling_unit >= 1),
    CONSTRAINT chk_global_tax_rate_positive CHECK (tax_rate >= 0.00)
);

CREATE INDEX IF NOT EXISTS idx_global_medicines_name ON global_medicines (lower(name));
CREATE INDEX IF NOT EXISTS idx_global_medicines_generic ON global_medicines (lower(generic_name));
CREATE INDEX IF NOT EXISTS idx_global_medicines_status ON global_medicines (status);
CREATE INDEX IF NOT EXISTS idx_global_medicines_barcode ON global_medicines (barcode) WHERE barcode IS NOT NULL;

-- 2. Global Medicine Suggestions Table (Silent store owner submission queue)
CREATE TABLE IF NOT EXISTS global_medicine_suggestions (
    id UUID PRIMARY KEY,
    business_id UUID NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    product_id UUID REFERENCES products(id) ON DELETE SET NULL,
    name VARCHAR(200) NOT NULL,
    generic_name VARCHAR(255),
    brand_name VARCHAR(100),
    manufacturer VARCHAR(150),
    dosage_form VARCHAR(50) NOT NULL,
    strength VARCHAR(50),
    base_unit VARCHAR(30) NOT NULL,
    selling_unit VARCHAR(50) NOT NULL DEFAULT 'Unit',
    units_per_selling_unit INTEGER NOT NULL DEFAULT 1,
    hsn_code VARCHAR(20),
    tax_rate NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    prescription_required BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING', -- PENDING, APPROVED, REJECTED
    admin_notes TEXT,
    reviewed_by UUID,
    reviewed_at TIMESTAMPTZ,
    global_medicine_id UUID REFERENCES global_medicines(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_global_suggestions_status ON global_medicine_suggestions (status);
CREATE INDEX IF NOT EXISTS idx_global_suggestions_business ON global_medicine_suggestions (business_id);
CREATE INDEX IF NOT EXISTS idx_global_suggestions_created ON global_medicine_suggestions (created_at DESC);

